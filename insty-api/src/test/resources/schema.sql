CREATE SCHEMA IF NOT EXISTS web_service;

-- 파일
CREATE TABLE IF NOT EXISTS web_service.files
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    container_type  VARCHAR(50)  NOT NULL CHECK (container_type IN ('COURSE_THUMBNAIL','COURSE_PRACTICE_FILE','ANSWER_THUMBNAIL', 'QUESTION_IMAGE', 'ANSWER_IMAGE')),
    container_id    BIGINT       NOT NULL,
    name            VARCHAR(255) NOT NULL,
    original_name   VARCHAR(255) NOT NULL,
    content_type    VARCHAR(100) NOT NULL,
    size            BIGINT       NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS container_index
    ON web_service.files (container_type, container_id);

-- 사용자 관련
CREATE TABLE IF NOT EXISTS web_service.users
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(100)  NOT NULL,
    nickname           VARCHAR(30)   NOT NULL,
    password           VARCHAR(255)  NOT NULL,
    introduce          VARCHAR(4000),
    user_type          VARCHAR(15)   CHECK (user_type IN ('NONE', 'LEARNER', 'CREATOR')),
    is_deleted         BOOLEAN       NOT NULL,
    profileimage_id    BIGINT,
    deleted_at         TIMESTAMP(6) WITH TIME ZONE,
    is_email_agreed    BOOLEAN       NOT NULL,
    last_login_at      TIMESTAMP(6) WITH TIME ZONE,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    social_id          VARCHAR(150),
    social_type        VARCHAR(15)   CHECK (social_type IN ('KAKAO', 'NAVER', 'GOOGLE', 'GITHUB', 'APPLE', 'LINKEDIN'))
);

-- 사용자 알림 설정
CREATE TABLE IF NOT EXISTS web_service.user_notification_preferences
(
    id                                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                                 BIGINT       NOT NULL UNIQUE,
    user_mention_notification_enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    user_mention_email_enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    new_question_notification_enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    new_question_email_enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    new_answer_notification_enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    new_answer_email_enabled                BOOLEAN      NOT NULL DEFAULT TRUE,
    answer_accepted_notification_enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    answer_accepted_email_enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    requested_course_registration_notification_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    requested_course_registration_email_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at                              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    FOREIGN KEY (user_id) REFERENCES web_service.users(id) ON DELETE CASCADE
);

-- 강의 관련
CREATE TABLE IF NOT EXISTS web_service.courses (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL,
    title            VARCHAR(255) NOT NULL,
    description      TEXT,
    price            INTEGER NOT NULL,
    view_count       INTEGER NOT NULL DEFAULT 0,
    like_count       INTEGER NOT NULL DEFAULT 0,
    target_audience  VARCHAR(100),
    thumbnail_id     BIGINT,
    is_show          BOOLEAN NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    is_deleted       BOOLEAN NOT NULL DEFAULT false,
    FOREIGN KEY (user_id) REFERENCES web_service.users(id),
    FOREIGN KEY (thumbnail_id) REFERENCES web_service.files(id)
);

CREATE TABLE IF NOT EXISTS web_service.course_practice_files (
    course_id   BIGINT NOT NULL,
    file_id     BIGINT NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (course_id, file_id),
    FOREIGN KEY (course_id) REFERENCES web_service.courses(id),
    FOREIGN KEY (file_id) REFERENCES web_service.files(id)
);

CREATE TABLE IF NOT EXISTS web_service.tags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_name    VARCHAR(50) UNIQUE NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS web_service.course_tags (
    course_id   BIGINT NOT NULL,
    tag_id      BIGINT NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (course_id, tag_id),
    FOREIGN KEY (course_id) REFERENCES web_service.courses(id),
    FOREIGN KEY (tag_id) REFERENCES web_service.tags(id)
);

CREATE TABLE IF NOT EXISTS web_service.course_install_env_checklists (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     BIGINT NOT NULL,
    content       VARCHAR(255) NOT NULL,
    is_supported  BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS web_service.course_keypoints (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT NOT NULL,
    content     VARCHAR(500) NOT NULL
);

--커뮤니티 관련
CREATE TABLE IF NOT EXISTS web_service.community_questions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, -- 질문 게시글 ID
    course_id   BIGINT NOT null references web_service.courses(id), -- 강의 ID
    user_id     BIGINT NOT null references web_service.users(id), -- 사용자 ID
    title       VARCHAR(255) NOT NULL, -- 질문 게시글 제목
    content     TEXT NOT NULL, -- 질문 게시글 내용
    board_type  VARCHAR(20) NOT NULL DEFAULT 'QNA', -- 게시판 타입(QNA / COURSE)
    status      VARCHAR(15) NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING', 'ANSWERED', 'ACCEPTED')), -- 질문 상태
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 생성 시각
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 수정 시각
    is_deleted  BOOLEAN NOT NULL DEFAULT FALSE, -- 삭제 여부
    accepted_answer_id BIGINT -- 채택된 답변 ID
);

CREATE TABLE IF NOT EXISTS web_service.community_answers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, -- 답변 게시글 ID
    user_id         BIGINT NOT null references web_service.users(id), -- 사용자 ID
    question_id     BIGINT NOT NULL REFERENCES web_service.community_questions(id) ON DELETE CASCADE, -- 커뮤니티 게시글 ID (질문 참조)
    content         TEXT NOT NULL, -- 답변 내용
    answer_image_id BIGINT, -- 답변 이미지 ID (nullable)
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 생성 시각
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 수정 시각
    is_deleted      BOOLEAN NOT NULL DEFAULT FALSE, -- 삭제 여부
    is_accepted      BOOLEAN NOT NULL DEFAULT FALSE -- 채택 여부
);

CREATE TABLE IF NOT EXISTS web_service.community_question_files (
    question_id  BIGINT NOT NULL,
    file_id      BIGINT NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (question_id, file_id),
    FOREIGN KEY (question_id) REFERENCES web_service.community_questions(id) ON DELETE CASCADE,
    FOREIGN KEY (file_id) REFERENCES web_service.files(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS web_service.community_answers_files (
    answer_id  	 BIGINT NOT NULL,
    file_id      BIGINT NOT null,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (answer_id, file_id),
    FOREIGN KEY (answer_id) REFERENCES web_service.community_answers(id) ON DELETE CASCADE,
    FOREIGN KEY (file_id) REFERENCES web_service.files(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS web_service.mentions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    community_answer_id     BIGINT NOT NULL,
    mentioned_user_id       BIGINT NOT NULL,
    mentioner_user_id       BIGINT NOT NULL,
    created_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    FOREIGN KEY (community_answer_id) REFERENCES web_service.community_answers(id) ON DELETE CASCADE,
    FOREIGN KEY (mentioned_user_id) REFERENCES web_service.users(id) ON DELETE CASCADE,
    FOREIGN KEY (mentioner_user_id) REFERENCES web_service.users(id) ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS web_service.community_question_views (
    question_id     BIGINT NOT NULL,
    user_id         BIGINT NOT NULL,
    last_viewed_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (question_id, user_id),
    FOREIGN KEY (question_id) REFERENCES web_service.community_questions(id) ON DELETE CASCADE
);

-- 영상 관련
CREATE TABLE IF NOT EXISTS web_service.video_courses
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_uuid         UUID         UNIQUE NOT NULL,
    course_id          BIGINT,
    user_id            BIGINT       NOT NULL,
    s3key              VARCHAR(255) NOT NULL,
    extension          VARCHAR(10)  NOT NULL,
    original_file_name VARCHAR(150) NOT NULL,
    duration           INTEGER      NOT NULL DEFAULT 0,
    encoding_status    VARCHAR(100) NOT NULL CHECK (encoding_status IN ('WAITING', 'PROCESSING', 'COMPLETED', 'FAILED', 'FAILED_INVALID_VIDEO_LENGTH', 'FAILED_NOT_FOUND_VOICE')),
    encoding_at        TIMESTAMP,
    analysis_status    VARCHAR(100) NOT NULL CHECK (analysis_status IN ('WAITING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    analysis_at        TIMESTAMP,
    created_at         TIMESTAMP    NOT NULL,
    updated_at         TIMESTAMP    NOT NULL,
    is_deleted         BOOLEAN      NOT NULL DEFAULT false,
    FOREIGN KEY (course_id) REFERENCES web_service.courses(id),
    FOREIGN KEY (user_id) REFERENCES web_service.users(id)
);

CREATE TABLE IF NOT EXISTS web_service.video_questions
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_uuid              UUID         UNIQUE NOT NULL,
    community_question_id   BIGINT,
    user_id                 BIGINT       NOT NULL,
    s3key                   VARCHAR(255) NOT NULL,
    extension               VARCHAR(10)  NOT NULL,
    original_file_name      VARCHAR(150) NOT NULL,
    duration                INTEGER      NOT NULL DEFAULT 0,
    encoding_status         VARCHAR(100) NOT NULL CHECK (encoding_status IN ('WAITING', 'PROCESSING', 'COMPLETED', 'FAILED', 'FAILED_INVALID_VIDEO_LENGTH', 'FAILED_NOT_FOUND_VOICE')),
    encoding_at             TIMESTAMP,
    created_at              TIMESTAMP    NOT NULL,
    updated_at              TIMESTAMP    NOT NULL,
    is_deleted              BOOLEAN      NOT NULL DEFAULT false,
    FOREIGN KEY (community_question_id) REFERENCES web_service.community_questions(id),
    FOREIGN KEY (user_id) REFERENCES web_service.users(id)
    );

CREATE TABLE IF NOT EXISTS web_service.video_answers
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_uuid              UUID         UNIQUE NOT NULL,
    community_answer_id   BIGINT,
    user_id                 BIGINT       NOT NULL,
    s3key                   VARCHAR(255) NOT NULL,
    extension               VARCHAR(10)  NOT NULL,
    original_file_name      VARCHAR(150) NOT NULL,
    duration                INTEGER      NOT NULL DEFAULT 0,
    encoding_status         VARCHAR(100) NOT NULL CHECK (encoding_status IN ('WAITING', 'PROCESSING', 'COMPLETED', 'FAILED', 'FAILED_INVALID_VIDEO_LENGTH', 'FAILED_NOT_FOUND_VOICE')),
    encoding_at             TIMESTAMP,
    created_at              TIMESTAMP    NOT NULL,
    updated_at              TIMESTAMP    NOT NULL,
    is_deleted              BOOLEAN      NOT NULL DEFAULT false,
    FOREIGN KEY (community_answer_id) REFERENCES web_service.community_answers(id),
    FOREIGN KEY (user_id) REFERENCES web_service.users(id)
);

CREATE TABLE IF NOT EXISTS web_service.video_encodings
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_uuid      UUID          UNIQUE   NOT NULL,
    format          VARCHAR(10)   NOT NULL,
    encoding_s3_key VARCHAR(500) NOT NULL,
    created_at      TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS web_service.course_progress(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    FOREIGN KEY (course_id) REFERENCES web_service.courses(id),
    FOREIGN KEY (user_id) REFERENCES web_service.users(id),
    CONSTRAINT uq_course_progress_user_course UNIQUE (user_id, course_id, status)
);
CREATE INDEX IF NOT EXISTS idx_course_progress_user ON web_service.course_progress (user_id);
CREATE INDEX IF NOT EXISTS idx_course_progress_course ON web_service.course_progress (course_id);


CREATE TABLE IF NOT EXISTS web_service.notifications
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    type            VARCHAR(50)  NOT NULL,
    title           VARCHAR(255) NOT NULL,
    message         TEXT,
    redirect_url    VARCHAR(255),
    state           VARCHAR(50)  NOT NULL CHECK (state IN ('UNREAD', 'READ', 'DELETED')),
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    FOREIGN KEY (user_id) REFERENCES web_service.users(id) ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS web_service.user_notification_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    notification_type VARCHAR(50) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_user_notification_settings UNIQUE (user_id, notification_type, channel),

    FOREIGN KEY (user_id) REFERENCES web_service.users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_user_notification_settings_user
    ON web_service.user_notification_settings (user_id);

CREATE INDEX IF NOT EXISTS idx_user_notification_settings_type_channel
    ON web_service.user_notification_settings (notification_type, channel);
