CREATE SCHEMA IF NOT EXISTS shared;
CREATE SCHEMA IF NOT EXISTS web_service;

CREATE TABLE IF NOT EXISTS shared.video_courses
(
    is_deleted         BOOLEAN      NOT NULL,
    analysis_at        TIMESTAMP,
    created_at         TIMESTAMP    NOT NULL,
    encoding_at        TIMESTAMP,
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    updated_at         TIMESTAMP    NOT NULL,
    extension          VARCHAR(10)  NOT NULL,
    video_uuid         UUID         NOT NULL,
    analysis_status    VARCHAR(100) NOT NULL CHECK (analysis_status IN ('WAITING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    encoding_status    VARCHAR(100) NOT NULL CHECK (encoding_status IN ('WAITING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    s3key              VARCHAR(100) NOT NULL,
    thumbnail_url      VARCHAR(1000),
    original_file_name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS web_service.video_encodings
(
    created_at      TIMESTAMP     NOT NULL,
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    format          VARCHAR(10)   NOT NULL,
    video_uuid      UUID          NOT NULL,
    encoding_s3_key VARCHAR(1000) NOT NULL
);